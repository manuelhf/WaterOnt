"""Live demonstrator for Colab: the real Python GraphRAG engine behind a Gradio UI.

    from wateront.gradio_app import build_app
    build_app(res).launch(share=True)     # share=True prints a public *.gradio.live link

Unlike the static page, this runs the actual pipeline, so it can use Claude for
query planning and answer generation (set ANTHROPIC_API_KEY) and shows the raw
JSON trace, including every graph triple behind each recommendation.
"""
from __future__ import annotations

import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from .graphrag import GraphRAG  # noqa: E402
from .pipeline import BuildResult  # noqa: E402

ACTION_COLOR = {"Replacement": "#A8231C", "Rehabilitation": "#7A4FB5", "Inspection": "#2F6FB0", "Monitor": "#A3AFB3"}
EXAMPLES = [
    "Which pipes should be replaced?",
    "Which unmonitored hydraulically critical mains have intolerable risk?",
    "Which pipes downstream of PRV-3 need intervention?",
    "Which mains in the tank zone should be replaced? top 5",
    "Which cast iron pipes are past their design life?",
]


def draw_map(res: BuildResult, highlight: dict[str, str] | None = None):
    wn = res.wn
    fig, ax = plt.subplots(figsize=(9, 5.5), dpi=110)
    for name, link in wn.links():
        a, b = link.start_node.coordinates, link.end_node.coordinates
        if highlight and name in highlight:
            continue
        ax.plot([a[0], b[0]], [a[1], b[1]], color="#C9D3D1" if highlight else "#8A979C", lw=0.8, zorder=1)
    for name, action in (highlight or {}).items():
        link = wn.get_link(name)
        a, b = link.start_node.coordinates, link.end_node.coordinates
        ax.plot([a[0], b[0]], [a[1], b[1]], color=ACTION_COLOR[action], lw=2.6, zorder=3)
    for n in wn.reservoir_name_list + wn.tank_name_list:
        x, y = wn.get_node(n).coordinates
        ax.scatter([x], [y], marker="s", s=40, color="#1F6F8B", zorder=4)
    ax.set_aspect("equal")
    ax.axis("off")
    if highlight:
        for act, col in ACTION_COLOR.items():
            if act in highlight.values():
                ax.plot([], [], color=col, lw=3, label=act)
        ax.legend(loc="lower left", frameon=False, fontsize=8)
    fig.tight_layout()
    return fig


def build_app(res: BuildResult, use_llm: bool = False):
    import gradio as gr

    engines = {False: GraphRAG(res.kg, use_llm=False)}

    def engine(llm: bool) -> GraphRAG:
        if llm not in engines:
            engines[llm] = GraphRAG(res.kg, use_llm=True)
        return engines[llm]

    def answer(question: str, llm: bool):
        if not question.strip():
            return "Type a question, or pick an example.", draw_map(res), "{}"
        ans = engine(llm).ask(question)
        hl = {e.facts["pipe"]: e.action for e in ans.recommendations}
        note = ""
        if ans.unsupported_citations:
            note = f"\n\n**Citation check failed** for {', '.join(ans.unsupported_citations)}: not in the retrieved evidence."
        header = f"*Generated by: {ans.generator}.*\n\n"
        return header + ans.text.replace("\n", "\n\n") + note, draw_map(res, hl), json.dumps(ans.to_dict(), indent=1, default=str)

    with gr.Blocks(title="WaterOnt GraphRAG") as app:
        gr.Markdown(f"## WaterOnt GraphRAG on {res.network_id}\nAsk a maintenance question. Answers come from the "
                    "knowledge graph; each recommendation cites the rule and policy clauses behind it. "
                    "Asset records are synthetic.")
        with gr.Row():
            q = gr.Textbox(label="Question", placeholder=EXAMPLES[0], scale=4)
            llm = gr.Checkbox(label="Use Claude (needs ANTHROPIC_API_KEY)", value=use_llm, scale=1)
        btn = gr.Button("Ask", variant="primary")
        gr.Examples(EXAMPLES, inputs=q)
        with gr.Row():
            out = gr.Markdown()
            plot = gr.Plot(value=draw_map(res))
        with gr.Accordion("Full trace (plan, facts and graph paths as JSON)", open=False):
            trace = gr.Code(language="json")
        btn.click(answer, [q, llm], [out, plot, trace])
        q.submit(answer, [q, llm], [out, plot, trace])
    return app
